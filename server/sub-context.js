"use strict";
/* ============================================================
   子智能体运行上下文（P5）
   ------------------------------------------------------------
   编排同层是**并行**的，所以"当前这一步"的归属绝不能挂在 agent 实例字段上：
   两个兄弟会互相踩（谁最后进来算谁，前面那个的工具就写进了别人的白板/认领集）。
   与 convContext 同一个办法：AsyncLocalStorage 把这一趟异步调用链绑到一份上下文上，
   深层工具 handler 取到的就是自己那一份。
   ------------------------------------------------------------
   里面装什么：
     label   这一步对外的名字（步骤名 / 子任务首句），冲突回执里要写它是谁挡了谁
     board   本次编排的共享白板
     owned   这一步已认领改盘权的文件路径（Set）
     report  编排器传进来的出参对象，结束时回填改动/冲突，供结构化汇报用
   ============================================================ */
const { AsyncLocalStorage } = require("async_hooks");

const subContext = new AsyncLocalStorage();

/* 不在子智能体里时返回 null —— 调用方必须能区分"没有上下文"和"上下文里是空的" */
function currentSub() {
  return subContext.getStore() || null;
}

module.exports = { subContext, currentSub };
