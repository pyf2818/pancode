let currentLang = localStorage.getItem("cw-lang") || "zh";

/* 插值走 {name} 占位：状态栏「行 1, 列 1」这类文案如果各自拼字符串，
   英文里 "Ln 1, Col 1" 的语序就得在每个调用点重抄一遍。 */
function t(key, vars) {
  let s = (LANGS[currentLang] && LANGS[currentLang][key]) || LANGS.zh[key] || key;
  if (vars) s = String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined || vars[k] === null ? m : String(vars[k])));
  return s;
}

/* 服务端（agent.state / tool.end 的 label）以中文原文为准 —— 引擎按用户跑，不知道界面语言。
   这里按 LANGS.zh 的值反查键，命中就按当前界面语言重渲染，没命中原样返回（宁可留中文，不留空白）。
   带占位符的动态语句（限流倒计时）走 labelKey，不依赖这条反查。 */
function getLang() { return currentLang; }

let zhIndex = null;
function tr(zh) {
  if (!zh || currentLang === "zh") return zh;
  if (!zhIndex) {
    zhIndex = new Map();
    for (const k in LANGS.zh) if (!zhIndex.has(LANGS.zh[k])) zhIndex.set(LANGS.zh[k], k);
  }
  const key = zhIndex.get(zh);
  return key ? t(key) : zh;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem("cw-lang", lang);
  applyI18n();
  langHooks.forEach((f) => { try { f(); } catch (e) {} });
  // 切换语言后重渲染动态区域（文件树 / 会话列表），使文案同步；历史聊天消息不翻译
  if (typeof renderTree === "function") { try { renderTree(); } catch (e) {} }
  if (typeof renderConvList === "function") { try { renderConvList(); } catch (e) {} }
  if (typeof window.refreshSidebar && typeof window.refreshSidebar === "function") { try { window.refreshSidebar(); } catch (e) {} }
}

/* 状态栏「行 1, 列 1」「0 错误」这类是 JS 拼出来的，不在 [data-i18n] 的覆盖范围里。
   注册成钩子：注册即执行一次（开机就是当前语言），切语言时再执行一次
   —— 否则空闲时切过去，这些行要等到下一次事件才变色。 */
const langHooks = [];
function onLang(fn) { try { fn(); } catch (e) {} langHooks.push(fn); return fn; }

function applyI18n() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    const val = t(key);
    if (el.tagName === "INPUT" && el.type === "text") el.placeholder = val;
    else if (el.tagName === "TEXTAREA") el.placeholder = val;
    else el.textContent = val;
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
  /* 屏幕阅读器读的 aria-label 也算界面文案，漏了它英文用户读不到按钮是干什么的。 */
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
}

